#!/usr/bin/env node
// Builds addon/content/emoji.txt, the catalogue the note pad's emoji picker
// reads. Run it again to pick up a new Unicode release:
//
//   node scripts/build-emoji-data.mjs
//
// Source: emojibase-data (https://github.com/milesj/emojibase), which is
// generated from the Unicode CLDR. Fetched from jsDelivr, so this needs a
// network connection; nothing at runtime does.
//
// Why a text file and not a JS module: the catalogue is ~230 KB and most
// sessions never open the picker. A module would be parsed on every startup;
// a file is read once, the first time someone clicks the button.
//
// Format, one emoji per line, tab separated:
//
//   <char>\t<group>\t<label>\t<vi label>\t<tags>\t<skin tones, | separated>
//
// `label` is the English name, shown as the cell's tooltip. It and the
// Vietnamese name are kept apart from the tags because a query that matches a
// NAME should outrank one that matches a tag -- "sách" is the name of 📕 and
// merely a tag of 🤓. `group` is
// emojibase's numbering (0 smileys, 1 people, 3 animals, 4 food,
// 5 travel, 6 activities, 7 objects, 8 symbols, 9 flags; 2 is components and
// is dropped). Search terms are the English label and tags followed by the
// Vietnamese ones, lowercased and de-duplicated. Accent folding is NOT baked
// in -- the reader does it once at load, which keeps the file a third smaller.
// Lines starting with # are comments.
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const VERSION = "16";
const CDN = `https://cdn.jsdelivr.net/npm/emojibase-data@${VERSION}`;
const OUT = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
  "addon",
  "content",
  "emoji.txt",
);

async function getJSON(url) {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`${response.status} ${response.statusText} for ${url}`);
  }
  return response.json();
}

const [en, vi] = await Promise.all([
  getJSON(`${CDN}/en/compact.json`),
  getJSON(`${CDN}/vi/compact.json`),
]);

const viByHex = new Map(vi.map((entry) => [entry.hexcode, entry]));

const lines = [
  `# Emoji catalogue for the Paperly note pad.`,
  `# Generated by scripts/build-emoji-data.mjs from emojibase-data@${VERSION}`,
  `# (https://github.com/milesj/emojibase, CLDR data, MIT licence).`,
  `# Columns: char <tab> group <tab> label <tab> vi label <tab> tags <tab> skin tones`,
];

let kept = 0;
for (const entry of [...en].sort((a, b) => (a.order ?? 1e9) - (b.order ?? 1e9))) {
  // 2 is "component": the bare skin tone swatches and hair colours, which are
  // modifiers rather than emoji anyone means to type.
  if (entry.group === undefined || entry.group === 2) {
    continue;
  }
  const localized = viByHex.get(entry.hexcode);
  const label = `${entry.label ?? ""}`.trim();
  const viLabel = `${localized?.label ?? ""}`.trim();
  const terms = [];
  const seen = new Set([label.toLowerCase(), viLabel.toLowerCase()]);
  for (const term of [...(entry.tags || []), ...(localized?.tags || [])]) {
    const value = `${term ?? ""}`.toLowerCase().trim();
    if (value && !seen.has(value)) {
      seen.add(value);
      terms.push(value);
    }
  }
  // Only the five single-modifier variants. Emoji built from several people
  // take one modifier each and there is no single "tone" for them, so the
  // picker leaves those at their default rather than guessing.
  const skins = (entry.skins || [])
    .filter((skin) => (skin.hexcode.match(/1F3F[B-F]/g) || []).length === 1)
    .map((skin) => skin.unicode);
  lines.push(
    [
      entry.unicode,
      entry.group,
      label,
      viLabel,
      terms.join(" "),
      skins.join("|"),
    ].join("\t"),
  );
  kept += 1;
}

const text = `${lines.join("\n")}\n`;
await writeFile(OUT, text, "utf8");
console.log(
  `Wrote ${kept} emoji to ${path.relative(process.cwd(), OUT)} (${(
    Buffer.byteLength(text) / 1024
  ).toFixed(0)} KB)`,
);
